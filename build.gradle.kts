    val replaceProperties = mapOf(
        "minecraft_version" to providers.gradleProperty("minecraft_version").get(),
        "minecraft_version_range" to providers.gradleProperty("minecraft_version_range").get(),
        "neo_version" to providers.gradleProperty("neo_version").get(),
        "mod_id" to modId,
        "mod_name" to providers.gradleProperty("mod_name").get(),
        "mod_license" to providers.gradleProperty("mod_license").get(),
        "mod_version" to providers.gradleProperty("mod_version").get(),
        "kff_version_range" to providers.gradleProperty("kff_version_range").get(),
    )
    inputs.properties(replaceProperties)
    filesMatching("META-INF/neoforge.mods.toml") {
        expand(replaceProperties)
    }
}

// ---------------------------------------------------------------------------
// copyNative — stage the MCDR native DLL into the mod resources
// ---------------------------------------------------------------------------
// `MCDR\` (the native library) and `Illusion\` (this mod) are INDEPENDENTLY
// managed repositories, so a build of this project may legitimately run with no
// native output present at all: a fresh clone, CI that only builds the JVM half,
// or a developer who has not run MSBuild yet. This task therefore NEVER fails
// the build -- it stages MCDR.dll when it can find one, and logs a warning and
// skips when it cannot.
//
// The DLL is staged at the RESOURCE ROOT because MCDR_ABI.extractLibrary() looks
// it up as `/MCDR.dll` on the classpath -- which resolves both from the packaged
// mod JAR and from build/resources/main during `runClient`.
//
// Build the native half first (Visual Studio 2026 / MSVC v145, C++23):
//   msbuild MCDR\MCDR.vcxproj /p:Configuration=Release /p:Platform=x64
val mcdrNativeDir = file("../MCDR")
val mcdrNativeConfigs = listOf("x64_Release", "x64_Debug")

val copyNative = tasks.register("copyNative") {
    group = "build"
    description = "Stages MCDR.dll into the mod resources; skips (never fails) when the native build output is absent."
    // Everything the action needs is captured HERE, by value. A `doLast` lambda
    // that reads a script-level `val` captures the script instance itself, and
    // with `org.gradle.configuration-cache=true` the build then fails with
    // "cannot serialize Gradle script object references" (the Groovy script did
    // not have this problem: its closures were resolved dynamically).
    val outDir = layout.buildDirectory.dir("generated/native").get().asFile
    val nativeDir: File = mcdrNativeDir
    val nativeConfigs: List<String> = mcdrNativeConfigs
    outputs.dir(outDir)
    // Always re-run: the copy is trivial, and a stale staged DLL is far more
    // expensive to diagnose than the copy is to repeat.
    outputs.upToDateWhen { false }
    doLast {
        try {
            outDir.mkdirs()
            val candidates = nativeConfigs.map { File(nativeDir, "target/$it/MCDR.dll") }
            val src = candidates.firstOrNull { it.isFile }
            if (src == null) {
                logger.warn("[copyNative] MCDR.dll not found; looked in: ${candidates.joinToString(", ")}. " +
                    "Skipping native staging -- build MCDR with MSBuild if the D3D12 backend is needed.")
                return@doLast
            }
            val dst = File(outDir, "MCDR.dll")
            src.copyTo(dst, overwrite = true)
            logger.lifecycle("[copyNative] staged $src -> $dst (${dst.length()} bytes)")
            // 崩溃栈符号化要求 MCDR.pdb 与 MCDR.dll 同目录（见 d3d12_device.cpp 的 P306c）：
            // 开发运行时把它放进 run/dxrmc/，native 崩溃日志就能直接给到 文件:行。
            // 只进 run/，不进 JAR —— PDB 十几 MB，对发行版没有意义。
            val pdbSrc = File(src.parentFile, "MCDR.pdb")
            if (pdbSrc.isFile) {
                val runDir = File(nativeDir.parentFile, "Illusion/run/dxrmc")
                runDir.mkdirs()
                // DLL 也一起放进 run/：运行时会按字节比较重新解包，但把两者成套落盘可以
                // 保证"崩溃时用到的 DLL"与"手边的 PDB"永远是同一次构建（否则解析出来的
                // 源码行会是错的）。
                src.copyTo(File(runDir, "MCDR.dll"), overwrite = true)
                val pdbDst = File(runDir, "MCDR.pdb")
                // 无条件覆盖：PDB 与 DLL 版本必须严格一致，留一份旧 PDB 会让崩溃栈
                // 解析到错误的源码行 —— 那种错误比没有符号更浪费时间。
                pdbSrc.copyTo(pdbDst, overwrite = true)
                logger.lifecycle("[copyNative] staged MCDR.dll + MCDR.pdb -> $runDir")
            }
        } catch (t: Throwable) {
            // Independently managed repos: a missing, locked or half-written native
            // output must never break the JVM build.
            logger.warn("[copyNative] skipped: $t")
        }
    }
}

// Feed the staged directory into the main resource set so the DLL ends up in
// build/resources/main and inside the mod JAR.
sourceSets.named("main") {
    resources.srcDir(copyNative)
}

// ---------------------------------------------------------------------------
// Third-party SDK runtimes: what ships inside the JAR, and what does not
// ---------------------------------------------------------------------------
// MCDR_ABI.extractLibrary() writes MCDR.dll into `<user.dir>/dxrmc/`, and the
// Windows loader resolves a native library's LoadLibrary calls from the
// *application* directory first -- so anything MCDR.dll loads at run time has to
// sit in that same `dxrmc/` folder. PATH is not enough: the application directory
// and the system directory both precede it in the search order, which is why a
// PATH-only experiment reports "not found" even with the files present on disk
// (known_bugs.md B14).
//
// TWO LISTS, and the split is both a licensing and a release-contents decision:
//
//   vendorJarLibs  -- REDISTRIBUTABLE and SHIPPED: these ride inside the released
//                     mod JAR as resources and are extracted to `dxrmc/` at startup
//                     by MCDR_ABI.extractVendorResources(). Each entry ships its own
//                     licence text as `LICENSE-<licenseName>.txt`:
//                       * XeSS      -- Intel Simplified Software License (permits
//                                      binary redistribution with the notice);
//                       * D3D12Core -- Microsoft DirectX / Agility SDK terms;
//                       * DXC       -- LLVM/NCSA (vcpkg `directx-dxc` copyright).
//                     The user asked for the FSR (AMD FidelityFX) runtimes to be
//                     absent from release builds (2026-10-20), and NVIDIA's RTX SDKs
//                     licence forbids redistribution outright.
//                     P216 (2026-10-25): D3D12Core.dll + dxcompiler.dll + dxil.dll are
//                     now mandatory in the JAR -- the graphics pipeline hard-requires
//                     SM 6.9 with no SM 5.1 fallback, and neither the Agility core nor
//                     DXC can be assumed to exist on a player's machine.
//
//   vendorDevLibs  -- DEVELOPMENT ONLY, never packed. `copyVendorDlls` stages them
//                     into `run/dxrmc/` so a dev client can exercise every vendor.
//                     NVIDIA: RTX SDKs licence clause 4(e) forbids using the SDK
//                     "in any manner that would cause it to become subject to an
//                     open source software license" -- listing redistribution at no
//                     charge, which is what LGPL-2.1 requires. AMD FidelityFX: the
//                     binaries are redistributable, but the release build no longer
//                     ships them; when they are missing the FSR probe reports
//                     itself unavailable and the renderer falls back.
data class VendorJarLib(val dir: File, val files: List<String>, val license: File?, val licenseName: String)

