// Expands the declared replace properties in the resource targets below; a missing property
// fails the build. Placeholders use Groovy's SimpleTemplateEngine (${}) notation.
// META-INF/neoforge.mods.toml is the only resource in this project that carries placeholders,
// and it lives in src/main/resources like every other resource: expanding it in place with
// filesMatching keeps a single copy of that path in the resource set, whereas a separate
// ProcessResources task feeding an extra resource srcDir fails with
// "Entry META-INF/neoforge.mods.toml is a duplicate" as soon as both directories carry it.
