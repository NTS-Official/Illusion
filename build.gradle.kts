// ---------------------------------------------------------------------------
// stageVendorLibs -- put the redistributable SDK runtimes INTO the mod JAR
// ---------------------------------------------------------------------------
// The mod JAR cannot reference these by path: a released mod is one file, and
// `gradlew build` runs long before anything is unzipped. So the DLLs ride inside
// the JAR as ordinary resources and MCDR_ABI pulls them out at startup.
//
// `vendor/manifest.txt` exists because a JAR directory cannot be enumerated
// without knowing every name in advance, and hard-coding nine file names in two
// places is how the two lists drift apart. The manifest is written here, at the
// moment the files are staged, so it cannot disagree with what was packaged.
//
// The staging root is the *parent* of `vendor/`, and the resource-set srcDir
// below points at that parent rather than at the module root: `processResources`
// strips the srcDir prefix, so declaring the folder that directly holds the DLLs
// would flatten ten files into the JAR root instead of nesting them under
// `vendor/`. Flat also means they can never be found again -- the extractor looks
// them up as `/vendor/<name>`.
//
// It must also be declared as an output DIRECTORY, not just `manifest.txt`:
// `srcDir(taskProvider)` harvests exactly what the task declares, so a
// manifest-only declaration silently shipped a manifest with no DLLs next to it.
//
// Like copyNative this NEVER fails the build: a missing source just means the matching
// runtime is absent from the JAR. But note the severity changed with P216: a missing
// `MCDR\external\` (XeSS) only disables upscaling, while a missing
// `MCDR\vcpkg_installed\` (D3D12Core / DXC) makes the D3D12 backend unable to build a
// single graphics pipeline -- the warning below is then a release blocker, not a notice.
val vendorJarRoot = layout.buildDirectory.dir("generated/vendorJar")
val vendorJarDir = vendorJarRoot.map { it.dir("vendor") }
val stageVendorLibs = tasks.register("stageVendorLibs") {
    group = "build"
    description = "Stages the redistributable SDK runtimes (XeSS, D3D12Core, DXC) + licences as mod JAR resources."
    // Captured by value below: a `doLast` lambda that reads a script-level `val`
    // captures the script instance, and the configuration cache refuses to
    // serialise that ("cannot serialize Gradle script object references").
    val root = vendorJarDir.get().asFile
    val jarLibs: List<VendorJarLib> = vendorJarLibs
    outputs.dir(root)
    outputs.upToDateWhen { false }

    doLast {
        try {
            root.mkdirs()
            // 变量名不叫 `manifest`：Groovy 版的 `doLast` 闭包会把 `manifest` 解析到 Task 自己的
            // 属性上（已踩过坑）。Kotlin 里不再委托给 Task，但保留 `manifestEntries` 这个名字，
            // 免得以后有人改回 Groovy 时又踩一次。
            val manifestEntries = mutableListOf<String>()
            var staged = 0
            val missing = mutableListOf<String>()
            jarLibs.forEach { entry ->
                val srcDir = entry.dir
                if (!srcDir.isDirectory) {
                    missing += "$srcDir (目录不存在)"
                    return@forEach
                }
                entry.files.forEach file@{ name ->
                    val src = File(srcDir, name)
                    if (!src.isFile) {
                        missing += src.toString()
                        return@file
                    }
                    val dst = File(root, name)
                    if (!dst.isFile || dst.length() != src.length()) {
                        src.copyTo(dst, overwrite = true)
                        staged++
                    }
                    manifestEntries += "vendor/$name"
                }
                val lic = entry.license
                if (lic != null && lic.isFile) {
                    val name = "LICENSE-${entry.licenseName}.txt"
                    val dst = File(root, name)
                    if (!dst.isFile || dst.length() != lic.length()) {
                        lic.copyTo(dst, overwrite = true)
                        staged++
                    }
                    manifestEntries += "vendor/$name"
                } else {
                    missing += "licence for $srcDir ($lic)"
                }
            }
            val mf = File(root, "manifest.txt")
            mf.writeText(manifestEntries.joinToString("\n") + "\n")
            // 删掉上次阶段化留下、这次不再打包的文件。发行包不再含 FidelityFX 之后，
            // 旧的 amd_fidelityfx_*.dll 仍躺在 build/generated/vendorJar/vendor/ 里，
            // processResources 会把它原样打回 JAR —— 清单之外的条目一律清掉。
            val keep = manifestEntries.mapTo(HashSet()) { it.substringAfterLast('/') }
            keep += "manifest.txt"
            (root.listFiles() ?: emptyArray()).forEach { stale ->
                if (stale.isFile && stale.name !in keep) {
                    stale.delete()
                    logger.lifecycle("[stageVendorLibs] pruned stale ${stale.name}")
                }
            }
            logger.lifecycle("[stageVendorLibs] ${manifestEntries.size} resource(s) in the mod JAR " +
                "($staged copied, rest already current)")
            if (missing.isNotEmpty()) {
                logger.warn("[stageVendorLibs] not staged (missing source): ${missing.joinToString(", ")}. " +
                    "XeSS would only disable upscaling, but a missing D3D12Core/dxcompiler/dxil means " +
                    "the D3D12 backend cannot build any graphics pipeline (SM 6.9 is mandatory, P216).")
            }
        } catch (t: Throwable) {
            logger.warn("[stageVendorLibs] skipped: $t")
        }
    }
}
// NOT `sourceSets.main.resources.srcDir stageVendorLibs`: a task provider added
// that way contributes each file with no path prefix, so the SDK runtimes land in
// the resource root and the extractor's `/vendor/<name>` lookups all miss. Two
// rounds of trying to name the staged folder so the prefix would survive both
// flattened instead, so the destination is stated outright here: the main resource
// set is left alone, and `processResources` copies the staged files into `vendor/`
// explicitly. `build/resources/main/vendor/` is then what `runClient` reads and
// what `jar` packages, with neither step left to infer a path.
//
// `from(stageVendorLibs)` passes the TASK, not the directory property: that is
// what wires the dependency and takes the task's declared outputs as the source.
// `from(vendorJarDir)` compiles and silently adds nothing -- processResources ran,
// reported success, and staged no vendor file at all.
tasks.named<ProcessResources>("processResources") {
    from(stageVendorLibs) {
        into("vendor")
    }
}

// ---------------------------------------------------------------------------
// copyVendorDlls -- dev-only SDK runtimes that must NOT ship
// ---------------------------------------------------------------------------
// The dev-side runtimes land here: NVIDIA DLSS (no redistribution right at all) and
// AMD FidelityFX (redistributable, but the release JAR no longer carries it). XeSS
// does not need this task — it is extracted from the JAR by the mod itself.
val copyVendorDlls = tasks.register("copyVendorDlls") {
    group = "build"
    description = "Dev-only: stages the NVIDIA (DLSS) and AMD (FidelityFX) runtime DLLs into run/dxrmc."
    // Captured by value, same reason as copyNative (configuration cache).
    val dxrmcDir = layout.projectDirectory.dir("run/dxrmc").asFile
    val devLibs: List<VendorDevLib> = vendorDevLibs
    outputs.dir(dxrmcDir)
    // Never up-to-date on the task level; the per-file size check below is what
    // keeps a no-op second run cheap. A task-level "up to date" would also skip
    // the (cheap) reporting, which is the point of running it.
    outputs.upToDateWhen { false }

    doLast {
        try {
            dxrmcDir.mkdirs()
            var staged = 0
            var alreadyThere = 0
            val missing = mutableListOf<String>()
            devLibs.forEach { entry ->
                val srcDir = entry.dir
                val pattern = entry.pattern
                if (!srcDir.isDirectory) {
                    missing += "$srcDir (目录不存在)"
                    return@forEach
                }
                val re = Pattern.compile("^" + pattern.replace(".", "\\.").replace("*", ".*") + "$")
                val matched = (srcDir.listFiles() ?: emptyArray()).filter {
                    it.isFile && re.matcher(it.name).matches()
                }
                if (matched.isEmpty()) {
                    missing += "$srcDir${File.separator}$pattern"
                    return@forEach
                }
                matched.forEach { src ->
                    val dst = File(dxrmcDir, src.name)
                    if (dst.isFile && dst.length() == src.length()) {
                        alreadyThere++
                        return@forEach
                    }
                    src.copyTo(dst, overwrite = true)
                    staged++
                    logger.lifecycle("[copyVendorDlls] staged ${src.name} (${"%,d".format(Locale.ROOT, src.length())} bytes)")
                }
            }
            logger.lifecycle("[copyVendorDlls] $staged copied, $alreadyThere already current")
            if (missing.isNotEmpty()) {
                logger.warn("[copyVendorDlls] not staged (missing source): ${missing.joinToString(", ")}. " +
                    "The matching SDK will report itself unavailable at run time.")
            }
        } catch (t: Throwable) {
            logger.warn("[copyVendorDlls] skipped: $t")
        }
    }
}

// 开发客户端要能看到全部厂商：XeSS 由 JAR 资源解出，AMD / NVIDIA 由上面的任务落进
// run/dxrmc/。挂在 runClient 上，是因为缺 DLL 时探针只会安静地报 unavailable——
// 那种「为什么 FSR/DLSS 不见了」很容易被误当成回归。任务本身按文件大小判重，
// 第二次运行只是一次文件列表比对。
tasks.matching { it.name == "runClient" }.configureEach {
    dependsOn(copyVendorDlls)
}

// ---------------------------------------------------------------------------
// jarALL -- TEST ONLY: `jar` plus every runtime DLL this machine has
// ---------------------------------------------------------------------------
// The release JAR deliberately carries only the three redistributable SDKs
// (`vendorJarLibs`); DLSS / FidelityFX / Streamline / NRC stay in `run/dxrmc/`
// because NVIDIA's RTX SDKs licence forbids shipping them and the user asked for
// FSR to be out of release builds (2026-10-20). Testing then needs three manual
// steps -- build, `copyNative`, `copyVendorDlls` -- plus a hand-copied DLL set.
//
// `jarALL` collapses that into one artifact: identical to `jar`, except that the
// `vendor/` tree also gets every dev-only DLL under `MCDR/lib/*`, and the manifest
// `MCDR_ABI.extractVendorResources()` reads lists all of them -- so launching that
// JAR unpacks the whole set next to MCDR.dll on its own.
//
// TEST ONLY, never publish: it redistributes binaries whose licences forbid it.
// Written by scanning `MCDR/lib/*/ *.dll` instead of naming files, so a new SDK
// folder is picked up without touching this script.
val vendorAllRoot = layout.buildDirectory.dir("generated/vendorJarAll")
val vendorAllDir = vendorAllRoot.map { it.dir("vendor") }

val stageVendorLibsAll = tasks.register("stageVendorLibsAll") {
    group = "build"
    description = "TEST ONLY: stages every runtime DLL (shipped SDKs + DLSS/FidelityFX/Streamline/NRC) into one vendor/ tree."
    // Captured by value for the configuration cache, same as the other staging tasks.
    val root = vendorAllDir.get().asFile
    val jarLibs: List<VendorJarLib> = vendorJarLibs
    val devLibRoot: File = file("../MCDR/lib")
    outputs.dir(root)
    outputs.upToDateWhen { false }

    doLast {
        try {
            root.mkdirs()
            // Not named `manifest`: the Groovy version of this task shadowed the Task property.
            val manifestEntries = mutableListOf<String>()
            val clashes = mutableListOf<String>()
            val missing = mutableListOf<String>()
            val stagedLengths = HashMap<String, Long>()
            // `MCDR/lib/xess` 里还有 libxess_dx11.dll（D3D11 口味）。MCDR 是 D3D12-only，
            // vendorDevLibs 早就把它排除在外面，这里保持一致，免得测试包里多一个永远用不上的 DLL。
            val skippedNames = setOf("libxess_dx11.dll")
            var staged = 0
            var totalBytes = 0L

            fun stage(src: File, asName: String) {
                if (asName in skippedNames) return
                val previous = stagedLengths[asName]
                if (previous != null) {
                    // 同一个 DLL 同时出现在 shipped 与 dev 目录时（libxess.*、external/xess/bin）
                    // 只留一份；大小不一致才值得警告。
                    if (previous != src.length()) clashes += "${src.absolutePath} (size ${src.length()} vs $previous)"
                    return
                }
                val dst = File(root, asName)
                if (!dst.isFile || dst.length() != src.length()) {
                    src.copyTo(dst, overwrite = true)
                    staged++
                }
                stagedLengths[asName] = dst.length()
                totalBytes += dst.length()
                manifestEntries += "vendor/$asName"
            }

            jarLibs.forEach { entry ->
                if (!entry.dir.isDirectory) {
                    missing += "$entry.dir (目录不存在)"
                    return@forEach
                }
                entry.files.forEach file@{ name ->
                    val src = File(entry.dir, name)
                    if (!src.isFile) {
                        missing += src.toString()
                        return@file
                    }
                    stage(src, name)
                }
                val lic = entry.license
                if (lic != null && lic.isFile) {
                    stage(lic, "LICENSE-${entry.licenseName}.txt")
                } else {
                    missing += "licence for ${entry.dir} ($lic)"
                }
            }

            // Dev-only SDKs: MCDR/lib/{dlss,fidelityfx,streamline,nrc}/*.dll.
            val devDlls = devLibRoot.listFiles().orEmpty()
                .filter { it.isDirectory }
                .flatMap { dir ->
                    (dir.listFiles() ?: emptyArray()).filter { it.isFile && it.name.endsWith(".dll", true) }
                }
                .sortedBy { it.absolutePath }
            if (devDlls.isEmpty()) missing += "$devLibRoot/**/*.dll (没有找到开发侧 DLL)"
            devDlls.forEach { stage(it, it.name) }

            val mf = File(root, "manifest.txt")
            mf.writeText(manifestEntries.joinToString("\n") + "\n")
            // Same stale sweep as stageVendorLibs: whatever is not in the manifest must not
            // ride into the JAR.
            val keep = manifestEntries.mapTo(HashSet()) { it.substringAfterLast('/') }
            keep += "manifest.txt"
            (root.listFiles() ?: emptyArray()).forEach { stale ->
                if (stale.isFile && stale.name !in keep) {
                    stale.delete()
                    logger.lifecycle("[stageVendorLibsAll] pruned stale ${stale.name}")
                }
            }
            logger.lifecycle(
                "[stageVendorLibsAll] ${manifestEntries.size} entries, " +
                    "${"%,d".format(Locale.ROOT, totalBytes)} bytes on disk ($staged copied, rest already current)")
            if (clashes.isNotEmpty()) {
                logger.warn("[stageVendorLibsAll] duplicate names, last one wins: ${clashes.joinToString(", ")}")
            }
            if (missing.isNotEmpty()) {
                logger.warn("[stageVendorLibsAll] not staged (missing source): ${missing.joinToString(", ")}")
            }
        } catch (t: Throwable) {
            logger.warn("[stageVendorLibsAll] skipped: $t")
        }
    }
}

