// ---------------------------------------------------------------------------
// Kotlin
// ---------------------------------------------------------------------------
// The whole JVM side of this mod is Kotlin except the mixins (Mixin cannot
// target Kotlin classes reliably, and the mixins only touch vanilla types).
//
// Three rules encoded here, all load-bearing and easy to break by accident:
//
//  1. jvmTarget MUST be 25. The Java toolchain is 25 and NeoForge 26.2 ships
//     Java 25 bytecode; letting Kotlin fall back to an older target makes
//     Gradle 9 fail with "Inconsistent JVM-target compatibility".
//  2. Never pass -Xjdk-release. On Kotlin 2.2.x it silently rewrote EVERY
//     java.lang.invoke.MethodHandle.invokeExact call site into a varargs call
//     (KT-72880), which destroys the FFM binding layer at runtime with no
//     compile error. It is fixed in 2.4.x, but there is no reason to use it.
//  3. jvmDefault = NO_COMPATIBILITY (the typed spelling of `-Xjvm-default=all`,
//     which Kotlin 2.4 warns about as deprecated) makes Kotlin emit real JVM
//     `default` methods for interface members that have a body, instead of
//     Java-8 "DefaultImpls" stubs. Without it, Java callers (and mixins) see the
//     method only through the synthetic `Foo$DefaultImpls` companion, which
//     reflection-based code and some bytecode tools do not follow; with it,
//     `javap` on the interface itself shows a real `default` method.
//
// Kotlin source files are always read as UTF-8; unlike JavaCompile there is no
// encoding options to set.
tasks.withType<KotlinCompile>().configureEach {
    compilerOptions.jvmTarget.set(JvmTarget.JVM_25)
    compilerOptions.jvmDefault.set(JvmDefaultMode.NO_COMPATIBILITY)
}

// IDEA no longer automatically downloads sources/javadoc jars for dependencies, so we need to
// explicitly enable the behavior.
//
// Assigned through the `IdeaModel.module` accessor rather than the `module { }` Action overload:
// inside a Gradle Kotlin script the lambda form makes the IDE's Gradle inspection bind the bare
// `module` identifier to the deprecated `Dependencies.module(group, name, version)` overload and
// report "Use single-string notation or DependencyFactory instead" on this block (sporadically,
// as the inspection's model reloads). Gradle 9.8.1's `IdeaModel.module(Action)` carries no
// deprecation at all; only `Dependencies.module` does. Both spellings configure the same object.
idea {
    module.isDownloadSources = true
    module.isDownloadJavadoc = true
}
